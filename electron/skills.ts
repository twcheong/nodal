// ── 스킬 워처 · TSL 컴파일 (main.ts 에서 이동) ──────────────────────────────
//
// 사용자/에이전트가 만든 .tskill 을 SKILL.md 로 컴파일하고, 워크스페이스의 skills/
// 폴더를 감시하다 변경되면 인덱스를 다시 만들어 렌더러에 알린다.
//
// **상태 3개(워처 핸들·디바운스 타이머·폴링 인터벌)가 한 덩어리로 움직인다.**
// 밖에서는 start/stop 으로만 만진다 — 핸들을 밖에 노출하면 stop 없이 덮어쓰는
// 경로가 생기고, 증상은 "스킬을 고쳐도 반영이 안 된다"(옛 워처가 살아 있음) 또는
// 파일 핸들 누수다.
