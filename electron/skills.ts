export interface SkillsDeps {
  getMainWindow: () => BrowserWindow | null
  /** 번들 스킬을 shared/ 로 심고, shared/ 를 사용자 폴더로 투영한다.
   *  ensureWorkspace 묶음 소유라 여기서는 호출만 한다 (Stage 4 제외 대상). */
  seedSharedFromBundle: () => string[]
  projectSharedIntoUser: (only?: string[]) => void
}

let deps: SkillsDeps | null = null

/** main.ts 가 기동 시 1회 호출한다. 안 부르면 첫 재컴파일에서 throw 한다. */
export function initSkills(d: SkillsDeps): void { deps = d }

function need(): SkillsDeps {
  if (!deps) throw new Error('skills.ts: initSkills() 가 먼저 불려야 한다')
  return deps
}

// ── TSL Compiler helpers — Twixy Skill Language 컴파일 래퍼 ───────
// .tskill(DSL 소스) → SKILL.md(에이전트가 직접 읽는 마크다운)로 변환.
// 실제 파서/코드젠은 tsl-compiler.ts 에 있다.

/** 디렉터리 트리 밑의 모든 .tskill 파일을 SKILL.md 로 컴파일.
 *  SKILL.md 가 이미 있고 원본보다 최신이면 스킵 (force=true 로 강제 재컴파일).
 *  실제로 (재)컴파일된 파일이 하나라도 있으면 true 반환. */
export function compileTskillFiles(dir: string, force = false): boolean {
  if (!fs.existsSync(dir)) return false
  let changed = false
  for (const entry of fs.readdirSync(dir)) {
    const full = path.join(dir, entry)
    if (fs.statSync(full).isDirectory()) {
      if (compileTskillFiles(full, force)) changed = true  // recurse
    } else if (entry.endsWith('.tskill')) {
      try {
        const outPath  = path.join(path.dirname(full), 'SKILL.md')
        const srcMtime = fs.statSync(full).mtimeMs
        // Skip if SKILL.md already exists and is newer than the .tskill source
        if (!force && fs.existsSync(outPath)) {
          const outMtime = fs.statSync(outPath).mtimeMs
          if (outMtime >= srcMtime) continue
        }
        const source = fs.readFileSync(full, 'utf8')
        const result = compileTSL(source, entry)
        if (result.ok && result.markdown) {
          fs.writeFileSync(outPath, result.markdown, 'utf8')
          // Pin SKILL.md mtime strictly after .tskill to prevent fs.watch feedback loops
          // (macOS FSEvents can fire .tskill events when sibling files in the same dir change)
          const after = new Date(srcMtime + 100)
          fs.utimesSync(outPath, after, after)
          console.log(`[tsl] Compiled ${entry} → SKILL.md`)
          changed = true
        } else {
          const errs = result.errors.map(e => e.message).join('; ')
          console.error(`[tsl] Compile error in ${entry}: ${errs}`)
        }
      } catch (e) {
        console.error(`[tsl] Failed to compile ${entry}:`, e)
      }
    }
  }
  return changed
}

// ── Skills watcher — 사용자/에이전트가 만든 스킬 자동 컴파일 ───────
// ~/.openclaw/workspace/twixy/skills/custom/ 아래의 .tskill 변경을 감시한다.
// OpenClaw 에이전트가 새 스킬 파일을 기록하면 즉시 SKILL.md 로 컴파일하고
// 렌더러에 skills-changed 이벤트를 쏴서 SkillsPanel 을 리프레시한다.

let skillsWatcher:       fs.FSWatcher | null  = null
let skillsDebounce:      NodeJS.Timeout | null = null
let skillsPollInterval:  NodeJS.Timeout | null = null

/** Regenerate SKILLS.md in the workspace root so the agent always knows the full skill list. */
export function regenerateSkillsIndex() {
  try {
    const skillsDir = path.join(getWorkspace(), 'skills')
    const lines: string[] = [
      '# Available Skills',
      '',
      'This file is auto-generated by Twixy. Do not edit manually.',
      '',
      '## How to use a skill',
      'When the user asks to use a skill by name:',
      '1. Find the matching skill below',
      '2. Read its `SKILL.md` at the listed path',
      '3. Follow the skill instructions exactly',
      '',
      '## Built-in Skills',
      '',
    ]

    const builtins: string[] = []
    const customs:  string[] = []

    if (fs.existsSync(skillsDir)) {
      for (const entry of fs.readdirSync(skillsDir)) {
        const dir    = path.join(skillsDir, entry)
        const mdPath = path.join(dir, 'SKILL.md')
        if (!fs.statSync(dir).isDirectory() || !fs.existsSync(mdPath)) continue
        const isCustom = fs.existsSync(path.join(dir, '.twixy-custom'))
        const content  = fs.readFileSync(mdPath, 'utf8')
        const descMatch = content.match(/^description:\s*"([^"]+)"/m)
        const desc = descMatch ? descMatch[1].slice(0, 120) : ''
        const row = `### \`${entry}\`\n**Path:** \`${mdPath}\`${desc ? `\n**Description:** ${desc}` : ''}\n`
        if (isCustom) { customs.push(row) } else { builtins.push(row) }
      }
    }

    if (builtins.length > 0) lines.push(...builtins)
    else lines.push('_No built-in skills found._\n')

    lines.push('## Custom Skills (user-created)', '')
    if (customs.length > 0) lines.push(...customs)
    else lines.push('_No custom skills installed yet._\n')

    const newContent = lines.join('\n')
    const skillsMdPath = path.join(getWorkspace(), 'SKILLS.md')
    let prev = ''
    try { prev = fs.readFileSync(skillsMdPath, 'utf8') } catch { /* first run */ }
    if (prev === newContent) return
    fs.writeFileSync(skillsMdPath, newContent, 'utf8')
    console.log('[skills-index] SKILLS.md regenerated')
  } catch (e) {
    console.error('[skills-index] failed:', e)
  }
}

function recompileAndNotify(customDir: string, forceNotify = false) {
  // New BUILT-IN skills can land while the app is running (dev: repo edit;
  // prod: app update). Re-seed + project them here (both steps are cheap and
  // missing-only) so a new skill reaches this user's workspace and SKILLS.md
  // without a relaunch — the watcher's 30s poll bounds the latency.
  try { need().projectSharedIntoUser(need().seedSharedFromBundle()) } catch (e) { console.warn('[skills-watcher] seed/project failed:', e) }
  const changed = compileTskillFiles(customDir)
  regenerateSkillsIndex()
  if (changed || forceNotify) need().getMainWindow()?.webContents.send('skills-changed')
}

export function startSkillsWatcher(workspace: string) {
  const customDir = path.join(workspace, 'skills')
  fs.mkdirSync(customDir, { recursive: true })

  const debounced = (forceNotify = false) => {
    if (skillsDebounce) clearTimeout(skillsDebounce)
    skillsDebounce = setTimeout(() => recompileAndNotify(customDir, forceNotify), 400)
  }

  try {
    skillsWatcher = fs.watch(customDir, { recursive: true, persistent: false }, (_, filename) => {
      if (!filename) return
      if (filename === '.twixy-custom') debounced(true)   // marker change → always notify
      else if (filename.endsWith('.tskill')) debounced()
    })
  } catch (err) {
    console.warn('[skills-watcher] fs.watch failed, using poll-only mode:', err)
  }

  // Safety-net poll every 30s — compileTskillFiles itself skips up-to-date files
  skillsPollInterval = setInterval(() => debounced(), 30_000)
  if (skillsPollInterval.unref) skillsPollInterval.unref()
}

export function stopSkillsWatcher() {
  if (skillsWatcher)      { skillsWatcher.close();          skillsWatcher      = null }
  if (skillsDebounce)     { clearTimeout(skillsDebounce);   skillsDebounce     = null }
  if (skillsPollInterval) { clearInterval(skillsPollInterval); skillsPollInterval = null }
}

/** Scan workspace/skills for valid .tskill files and return manifests */
export function scanSkillManifests(skillsDir: string, author: 'builtin' | 'user'): SkillManifest[] {
  const manifests: SkillManifest[] = []
  if (!fs.existsSync(skillsDir)) return manifests

  for (const entry of fs.readdirSync(skillsDir)) {
    const skillDir = path.join(skillsDir, entry)
    if (!fs.statSync(skillDir).isDirectory()) continue

    const tskillPath = path.join(skillDir, `${entry}.tskill`)
    const altPath    = path.join(skillDir, 'SKILL.md')  // fallback

    let added = false
    if (fs.existsSync(tskillPath)) {
      try {
        const source = fs.readFileSync(tskillPath, 'utf8')
        const result = compileTSL(source, `${entry}.tskill`)
        if (result.ok && result.metadata) {
          // Parse platforms from source (quick regex rather than full AST)
          const platforms = (source.match(/^  (INSTAGRAM|TIKTOK|YOUTUBE|TWITTER|LINKEDIN|GOOGLE_ANALYTICS|GOOGLE_ADS|META_ADS|NOTION|AIRTABLE|SLACK)/gm) ?? [])
            .map(l => l.trim()) as SkillManifest['platforms']

          const descM = source.match(/description:\s*"([^"]+)"/)
          const tagsM = source.match(/tags:\s*\[([^\]]+)\]/)
          const stageMatches = source.match(/^(COLLECT|ANALYZE|STRATEGIZE|EXECUTE|TRACK)\s+"/gm) ?? []
          const stages = [...new Set(stageMatches.map(l => l.trim().split(/\s+/)[0]))]
          const stepMatches = [...source.matchAll(/^(COLLECT|ANALYZE|STRATEGIZE|EXECUTE|TRACK)\s+"([^"]+)"/gm)]
          const steps = stepMatches.map(m => ({ type: m[1], label: m[2] }))

          manifests.push({
            name:        entry,
            displayName: result.metadata.skill,
            description: descM?.[1] ?? '',
            tags:        tagsM ? tagsM[1].split(',').map(t => t.trim()) : [],
            author,
            version:     result.metadata.version,
            platforms,
            stages,
            steps,
            sourceFile:  tskillPath.replace(getWorkspace(), ''),
          })
          added = true
        }
      } catch { /* skip */ }
    }
    // Fallback to SKILL.md — also runs when tskill compilation fails
    if (!added && fs.existsSync(altPath)) {
      try {
        const md   = fs.readFileSync(altPath, 'utf8')
        const nameM = md.match(/^# (.+)$/m)
        if (nameM) {
          manifests.push({
            name:        entry,
            displayName: nameM[1].trim(),
            description: md.split('\n')[2]?.trim() ?? '',
            tags:        [],
            author,
            version:     '1.0',
            platforms:   [],
            stages:      [],
            steps:       [],
            sourceFile:  (fs.existsSync(tskillPath) ? tskillPath : altPath).replace(getWorkspace(), ''),
          })
          added = true
        }
      } catch { /* skip */ }
    }
  }

  return manifests
}

// ── 번들 스킬 투영 — shared/skills → users/<uid>/skills ─────────────────────
//
// 예전 동작: **없는 것만 복사, 있으면 절대 안 건드린다.** 그래서 앱을 올려도 번들 스킬
// 수정이 이미 설치된 사용자에게 영영 도달하지 않았다 (`pptx` 가 한 달 넘게 8월 판으로
// 남아 있었다 — 새 설치에만 고쳐진 채 나갔다). 주석은 "Phase 3 에서 충돌 감지와 함께
// 명시적 pull 을 넣는다" 였고 그 Phase 3 은 오지 않았다.
//
// 지금 동작: **우리가 지난번에 넣어 준 바이트 그대로일 때만** 덮어쓴다. 기준값은 넣어
// 줄 때 sha256 으로 적어 둔다(`skills/.twixy-projected.json`) — mtime 으로 추측하지
// 않는다. 사용자가 고친 파일은 건드리지 않고 로그로 알린다.
//
// 권위는 `.tskill` 이다. `SKILL.md` 는 `npm run skills:compile` 이 만든 산출물이고
// 번들에 같이 들어오므로 짝으로 복사한다. 투영 뒤 `compileTskillFiles` 가 mtime 을 보고
// 필요하면 다시 만든다 — `.tskill` 만 새로 깔리고 `SKILL.md` 가 옛것으로 남는 상태는 없다.

/** 사용자 스킬 폴더 안의 기준값 장부. skills/ 를 통째로 지우면 같이 사라진다(= 새 설치처럼 다시 깔린다). */
export const PROJECTED_MANIFEST = '.twixy-projected.json'

/** `{ <skill>: { <file>: <sha256> } }` — 우리가 마지막으로 **넣어 준** 내용의 해시. */
export type ProjectedManifest = Record<string, Record<string, string>>

export type ProjectionAction =
  | 'copy'        // 사용자 폴더에 없다 → 새로 넣는다
  | 'up-to-date'  // 이미 번들과 같다 → 할 일 없다
  | 'update'      // 우리가 넣어 준 그대로다 → 새 번들로 덮는다
  | 'adopt'       // 기준값이 없다(업그레이드 첫 실행) → 덮되 원본을 .bak 로 남긴다
  | 'keep-local'  // 사용자가 고쳤다 → 건드리지 않는다

/** 파일 하나를 어떻게 할지. 이 판정이 이 기능의 전부다 — 나머지는 복사·로그다. */
export function projectionAction(
  userHash: string | null,
  shippedHash: string | undefined,
  bundleHash: string,
): ProjectionAction {
  if (userHash === null) return 'copy'
  if (userHash === bundleHash) return 'up-to-date'
  if (shippedHash === undefined) return 'adopt'
  return userHash === shippedHash ? 'update' : 'keep-local'
}

export function sha256File(p: string): string | null {
  try { return createHash('sha256').update(fs.readFileSync(p)).digest('hex') } catch { return null }
}

export function loadProjectedManifest(userSkillsDir: string): ProjectedManifest {
  try {
    const raw: unknown = JSON.parse(fs.readFileSync(path.join(userSkillsDir, PROJECTED_MANIFEST), 'utf8'))
    return raw && typeof raw === 'object' && !Array.isArray(raw) ? (raw as ProjectedManifest) : {}
  } catch { return {} }
}

/** 내용이 바뀐 경우에만 쓴다 — 이 파일도 skills 워처가 보고 있어서 매번 쓰면 재컴파일이 돈다. */
export function saveProjectedManifest(userSkillsDir: string, manifest: ProjectedManifest): void {
  const target = path.join(userSkillsDir, PROJECTED_MANIFEST)
  const next = JSON.stringify(manifest, null, 2)
  try {
    if (fs.readFileSync(target, 'utf8') === next) return
  } catch { /* 없으면 쓴다 */ }
  try { fs.writeFileSync(target, next, 'utf8') }
  catch (e) { console.warn('[twixy/skills] 기준값 장부 저장 실패:', e) }
}

export interface ProjectResult {
  copied: string[]
  updated: string[]
  adopted: string[]
  keptLocal: string[]
  userDeleted: string[]
  downgraded: boolean
}

/**
 * shared/skills 를 사용자 스킬 폴더로 투영한다.
 *
 * `only` 는 번들 스킬 이름 목록 — 팀원이 공유한 스킬은 자동 투영 대상이 아니다
 * (그쪽은 `pull-shared` 가 명시적으로 당긴다).
 */
export function projectBundledSkills(
  sharedSkillsDir: string,
  userSkillsDir: string,
  copyFile: (src: string, dst: string) => { ok: boolean; downgraded: boolean; err?: unknown },
  only?: string[],
): ProjectResult {
  const out: ProjectResult = { copied: [], updated: [], adopted: [], keptLocal: [], userDeleted: [], downgraded: false }
  if (!fs.existsSync(sharedSkillsDir)) return out
  fs.mkdirSync(userSkillsDir, { recursive: true })

  const shipped = loadProjectedManifest(userSkillsDir)
  const next: ProjectedManifest = { ...shipped }

  for (const skill of fs.readdirSync(sharedSkillsDir)) {
    if (only && !only.includes(skill)) continue
    const src = path.join(sharedSkillsDir, skill)
    const dst = path.join(userSkillsDir, skill)
    if (!fs.statSync(src).isDirectory()) continue

    if (!fs.existsSync(dst)) {
      // 한 번 넣어 준 적이 있는데 지금 없다 = 사용자가 지웠다. 되살리지 않는다.
      // (장부가 없던 시절에 지운 스킬은 구별할 수 없어 예전처럼 다시 깔린다 — 한 번뿐이다.)
      if (shipped[skill]) { out.userDeleted.push(skill); continue }
      fs.mkdirSync(dst, { recursive: true })
    }

    // `.tskill` 이 있으면 SKILL.md 는 **파생물**이다 — 해시로 보호하지 않는다. 투영 뒤
    // compileTskillFiles 가 그 자리에 다시 쓰므로, 해시로 보면 앱이 쓴 산출물이 "사용자가
    // 고친 파일" 로 보이고 그 스킬은 다시는 갱신되지 않는다(패키지 첫 실행에서 6개가 그렇게
    // 됐다). 사용자 편집 여부는 `.tskill` 로만 판정하고, `.tskill` 을 새로 깔 때만 번들의
    // SKILL.md 를 짝으로 같이 깐다. `.tskill` 이 없는 스킬은 SKILL.md 가 소스라 그대로 보호한다.
    const derivedMd = fs.existsSync(path.join(src, `${skill}.tskill`))
    let tskillWritten = false
    const record: Record<string, string> = {}
    // SKILL.md 를 맨 뒤로 — `.tskill` 을 깔았는지 안 뒤에 판단한다.
    const files = fs.readdirSync(src).sort((a, b) => Number(a === 'SKILL.md') - Number(b === 'SKILL.md'))
    for (const file of files) {
      const srcFile = path.join(src, file)
      const dstFile = path.join(dst, file)
      if (!fs.statSync(srcFile).isFile()) continue
      if (derivedMd && file === 'SKILL.md') {
        if (!tskillWritten && fs.existsSync(dstFile)) continue
        const r = copyFile(srcFile, dstFile)
        if (r.downgraded) out.downgraded = true
        if (!r.ok) console.warn(`[twixy/project] copy ${skill}/${file} failed:`, r.err)
        continue
      }
      const bundleHash = sha256File(srcFile)
      if (!bundleHash) continue
      const shippedHash = shipped[skill]?.[file]
      const action = projectionAction(sha256File(dstFile), shippedHash, bundleHash)

      if (action === 'up-to-date') { record[file] = bundleHash; continue }
      if (action === 'keep-local') {
        out.keptLocal.push(`${skill}/${file}`)
        record[file] = shippedHash!   // 기준값은 그대로 둔다 — 다음에도 "고친 파일" 로 본다
        continue
      }
      // 업그레이드 첫 실행에는 사용자가 고친 것과 옛 번들본을 **구별할 수 없다.**
      // 덮되 원본을 .bak 로 남긴다. 백업을 못 만들면 덮지 않는다 (파괴보다 낡은 게 낫다).
      if (action === 'adopt' && !backupOnce(dstFile)) { out.keptLocal.push(`${skill}/${file}`); continue }

      const r = copyFile(srcFile, dstFile)
      if (r.downgraded) out.downgraded = true
      if (!r.ok) { console.warn(`[twixy/project] copy ${skill}/${file} failed:`, r.err); continue }
      record[file] = bundleHash
      if (file === `${skill}.tskill`) tskillWritten = true
      out[action === 'copy' ? 'copied' : action === 'adopt' ? 'adopted' : 'updated'].push(`${skill}/${file}`)
    }
    next[skill] = record
  }

  saveProjectedManifest(userSkillsDir, next)
  logProjection(out)
  return out
}

/** 원본을 `<file>.bak` 로 한 번만 남긴다. 이미 있으면 그게 더 오래된 원본이므로 지키다. */
function backupOnce(file: string): boolean {
  const bak = `${file}.bak`
  if (fs.existsSync(bak)) return true
  try { fs.copyFileSync(file, bak); return true }
  catch (e) { console.warn(`[twixy/skills] ${path.basename(file)} 백업 실패 — 덮어쓰지 않는다:`, e); return false }
}

/** 조용히 넘어가면 안 되는 것들: 무엇을 건드렸고 무엇을 안 건드렸는가. */
// 투영은 기동 때 한 번이 아니라 스킬 워처의 30초 폴링마다 돈다. "보존"·"삭제" 는 상태라서
// 매번 같은 줄이 찍힌다 — 내용이 바뀔 때만 찍는다. (복사·갱신은 사건이라 매번 찍는다.)
let lastStateLog = ''

function logProjection(r: ProjectResult): void {
  if (r.copied.length)      console.log(`[twixy/skills] 새 스킬 ${r.copied.length}개 설치: ${r.copied.join(', ')}`)
  if (r.updated.length)     console.log(`[twixy/skills] 번들 갱신 적용 ${r.updated.length}개: ${r.updated.join(', ')}`)
  if (r.adopted.length)     console.log(`[twixy/skills] 기준값이 없어 번들본으로 맞춘 파일 ${r.adopted.length}개 (원본은 .bak 로 보관): ${r.adopted.join(', ')}`)
  const state = [
    r.keptLocal.length   ? `[twixy/skills] 로컬 수정본 ${r.keptLocal.length}개는 그대로 둔다 (번들 갱신 안 됨): ${r.keptLocal.join(', ')}` : '',
    r.userDeleted.length ? `[twixy/skills] 사용자가 지운 스킬 ${r.userDeleted.length}개는 되살리지 않는다: ${r.userDeleted.join(', ')}` : '',
  ].filter(Boolean).join('\n')
  if (state && state !== lastStateLog) console.log(state)
  lastStateLog = state
  if (r.downgraded)         console.log('[twixy/project] APFS clonefile not supported on this filesystem — using plain copy')
}

/** SkillsPanel 이 부르는 스킬 CRUD IPC 5개를 등록한다 (main.ts 에서 이동). import 시점 부작용 없음. */
export function registerSkillsIpc(): void {
  // ── TSL IPC — 스킬 CRUD & 컴파일 ─────────────────────────────────
  // SkillsPanel 이 이 핸들러들을 통해 스킬을 읽고/컴파일/설치/삭제/나열한다.
  // 설치 시 custom 폴더에 놓고 .twixy-custom 마커 파일을 쓰는 점이 중요.

  /** Read the .tskill source for a skill by name */
  ipcMain.handle('read-skill-source', (_e, name: string) => {
    const dir = path.join(getWorkspace(), 'skills', name)
    const tskillPath = path.join(dir, `${name}.tskill`)
    if (!isInside(path.join(getWorkspace(), 'skills'), tskillPath)) {
      return { ok: false, source: '', error: 'Invalid skill name' }
    }
    try {
      const source = fs.readFileSync(tskillPath, 'utf8')
      return { ok: true, source }
    } catch {
      return { ok: false, source: '', error: 'Source file not found' }
    }
  })

  /** Compile a .tskill source string and return the result (no file I/O) */
  ipcMain.handle('compile-tskill', (_e, payload: { source: string; filename: string }) => {
    return compileTSL(payload.source, payload.filename)
  })

  /** Install a custom skill: validate, write .tskill + SKILL.md to user/skills.
   *  Custom skills always land in the user workspace — never in shared/. To
   *  promote a custom skill to shared (team-wide), the user will open a Merge
   *  Request in Phase 2. For now, a name collision with a shared-cloned built-in
   *  is blocked to preserve non-destructiveness. */
  ipcMain.handle('install-skill', (_e, payload: { source: string; name: string }) => {
    // 이름 정규화는 렌더러(SkillsPanel)에만 있었다 — `../../x` 가 오면 skills/ 밖에 파일 3개를
    // 썼다. read-skill-source / delete-skill 과 같은 거부 문구로 맞춘다.
    try { safeSegment(payload?.name) }
    catch { return { ok: false, errors: [{ code: 'invalid_name', message: 'Invalid skill name' }] } }
    const filename = `${payload.name}.tskill`
    const result   = compileTSL(payload.source, filename)

    if (!result.ok || !result.markdown) {
      return { ok: false, errors: result.errors }
    }

    const skillDir     = path.join(getWorkspace(), 'skills', payload.name)
    const customMarker = path.join(skillDir, '.twixy-custom')
    // If a same-named skill exists in user/skills/ without the .twixy-custom
    // marker, it's a clone of a shared built-in — overwriting would silently
    // shadow the team version. Reject until the user either (a) renames their
    // custom skill, or (b) opens an MR to update the shared skill (Phase 2).
    if (fs.existsSync(skillDir) && !fs.existsSync(customMarker)) {
      return {
        ok: false,
        errors: [{
          code:    'name_conflict_with_shared',
          message: `A shared skill named "${payload.name}" already exists. Rename your skill, or open a Merge Request to update the shared version.`,
        }],
      }
    }

    fs.mkdirSync(skillDir, { recursive: true })
    fs.writeFileSync(path.join(skillDir, filename),   payload.source,  'utf8')
    fs.writeFileSync(path.join(skillDir, 'SKILL.md'), result.markdown, 'utf8')
    fs.writeFileSync(customMarker,                    '',              'utf8')
    console.log(`[tsl] Installed custom skill: ${payload.name}`)
    regenerateSkillsIndex()
    need().getMainWindow()?.webContents.send('skills-changed')
    return { ok: true, errors: [] }
  })

  /** Delete a custom skill by name */
  ipcMain.handle('delete-skill', (_e, name: string) => {
    const skillDir = path.join(getWorkspace(), 'skills', name)
    if (!isInside(path.join(getWorkspace(), 'skills'), skillDir)) {
      return { ok: false, error: 'Invalid skill name' }
    }
    if (!fs.existsSync(path.join(skillDir, '.twixy-custom'))) {
      return { ok: false, error: 'Cannot delete a built-in skill' }
    }
    if (fs.existsSync(skillDir)) {
      fs.rmSync(skillDir, { recursive: true, force: true })
      console.log(`[tsl] Deleted custom skill: ${name}`)
      regenerateSkillsIndex()
      need().getMainWindow()?.webContents.send('skills-changed')
    }
    return { ok: true }
  })

  /** List all installed skills (built-in + custom) */
  ipcMain.handle('list-skills', () => {
    const skillsDir = path.join(getWorkspace(), 'skills')
    const all = scanSkillManifests(skillsDir, 'builtin')
    // Re-tag user-created skills by presence of .twixy-custom marker
    return all.map(m => {
      const marker = path.join(skillsDir, m.name, '.twixy-custom')
      return fs.existsSync(marker) ? { ...m, author: 'user' as const } : m
    })
  })
}
