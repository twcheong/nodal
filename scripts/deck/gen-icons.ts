// Generates shared/deck/icons.ts from lucide-react's icon modules.
//
//   npx tsx scripts/deck/gen-icons.ts
//
// The deck icon set is a CURATED subset — a fixed roster the prompts can
// enumerate and the painters can trust, not all 5,800 lucide icons. Codegen
// (instead of hand-copying path data) keeps the shapes exactly lucide's and
// makes upgrading the icon library a re-run, not a transcription session.
// The output is committed: shared/ stays dependency-free and pure.

import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..')

/** Marketing-deck roster. Kebab-case lucide names. */
const ROSTER = [
  // growth & metrics
  'trending-up', 'trending-down', 'chart-column', 'chart-line', 'chart-pie', 'target', 'gauge', 'percent',
  // money
  'dollar-sign', 'credit-card', 'shopping-cart', 'shopping-bag', 'wallet', 'piggy-bank',
  // audience & people
  'users', 'user', 'user-plus', 'heart', 'thumbs-up', 'eye', 'message-circle', 'share-2',
  // channels & content
  'megaphone', 'mail', 'globe', 'smartphone', 'monitor', 'video', 'camera', 'image', 'play', 'mic',
  // work & process
  'calendar', 'clock', 'check', 'check-check', 'circle-check', 'list-checks', 'clipboard-list', 'flag',
  'rocket', 'zap', 'lightbulb', 'star', 'award', 'trophy', 'crown', 'gem',
  // structure & navigation
  'arrow-right', 'arrow-up-right', 'arrow-down-right', 'refresh-cw', 'repeat', 'link', 'search', 'filter',
  'layers', 'package', 'gift', 'map-pin', 'building-2', 'briefcase', 'handshake', 'scale',
  // caution
  'triangle-alert', 'circle-alert', 'shield', 'lock',
] as const

type IconNode = [string, Record<string, string | number>][]

function loadIcon(name: string): IconNode {
  const file = path.join(ROOT, 'node_modules/lucide-react/dist/esm/icons', `${name}.js`)
  const src = fs.readFileSync(file, 'utf8')
  // Some names are aliases (`filter.js` → `export { default } from './funnel.js'`).
  const alias = /export \{ default \} from '\.\/([\w-]+)\.js'/.exec(src)
  if (alias) return loadIcon(alias[1])
  const m = /const __iconNode = (\[[\s\S]*?\]);\n/.exec(src)
  if (!m) throw new Error(`cannot parse ${name}`)
  // The literal is plain JSON-ish JS: arrays, strings, numbers, object keys.
  // eslint-disable-next-line no-eval
  const node = (0, eval)(m[1]) as IconNode
  return node.map(([tag, attrs]) => {
    const { key: _key, ...rest } = attrs as Record<string, string | number> & { key?: string }
    return [tag, rest]
  })
}

const entries = ROSTER.map((name) => {
  const node = loadIcon(name)
  return `  '${name}': ${JSON.stringify(node)},`
})

const out = `// GENERATED by scripts/deck/gen-icons.ts — do not hand-edit.
//
// Shapes are lucide's (ISC license, https://lucide.dev) — a curated
// marketing-deck subset, committed so shared/ stays dependency-free and pure.
// Icons are 24×24 stroke outlines: stroke-width 2, round caps/joins, no fill.
//
// See shared/deck/page.ts for the purity rules that apply to this whole folder.

/** [svgTag, attrs] pairs inside a 24×24 viewBox. */
export type IconNode = [string, Record<string, string | number>][]

export const DECK_ICONS: Record<string, IconNode> = {
${entries.join('\n')}
}

export const ICON_NAMES = Object.keys(DECK_ICONS)

/** Unknown icon = hard error. A silently skipped icon leaves a hole the
 *  author cannot see; the error names the roster so the model can re-pick. */
export function iconNode(name: string): IconNode {
  const node = DECK_ICONS[name]
  if (!node) throw new Error(\`Unknown icon '\${name}'. Valid icons: \${ICON_NAMES.join(', ')}.\`)
  return node
}

/** Standalone SVG document for one icon — the exporter rasterizes this. */
export function iconSvg(name: string, colorHex: string, px: number): string {
  const inner = iconNode(name)
    .map(([tag, attrs]) =>
      \`<\${tag} \${Object.entries(attrs).map(([k, v]) => \`\${k}="\${v}"\`).join(' ')}/>\`)
    .join('')
  return (
    \`<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" width="\${px}" height="\${px}" \` +
    \`fill="none" stroke="#\${colorHex}" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">\${inner}</svg>\`
  )
}
`

fs.writeFileSync(path.join(ROOT, 'shared/deck/icons.ts'), out, 'utf8')
console.log(`shared/deck/icons.ts written — ${ROSTER.length} icons`)
