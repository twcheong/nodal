// 빌드 대상 제품을 코드에 구워 넣는다.
//
//   APP_MODE=nodal tsx scripts/write-product.ts
//
// 왜 env 를 런타임에 읽지 않는가: 패키징된 앱은 더블클릭으로 뜨므로 APP_MODE 가
// 없다. 예전엔 main 이 process.env.APP_MODE 를 런타임에 읽어서, Enterprise dmg 도
// 실제로는 일반 Twixy 로 떴다. 그래서 빌드 직전에 두 파일을 생성한다:
//
//   shared/product/current.generated.ts  현재 제품의 profile 을 re-export.
//                                        main(tsc/vite-electron)·renderer(vite)가 import.
//   tmp/product.json                     같은 profile 의 JSON 사본. TS 를 못 읽는
//                                        electron-builder.config.mjs · vite.config.ts 용.
//
//   --if-missing  이미 있으면 건드리지 않는다 (postinstall/test/lint 용 — 개발자가
//                 고른 모드를 덮어쓰지 않으면서 새 체크아웃은 깨지지 않게).
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'
import type { ProductProfile } from '../shared/product/types'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const OUT_TS   = path.join(ROOT, 'shared', 'product', 'current.generated.ts')
const OUT_MAIN = path.join(ROOT, 'shared', 'product', 'current.main.generated.ts')
const OUT_JSON = path.join(ROOT, 'tmp', 'product.json')

const writeIfChanged = (file: string, body: string) => {
  // 내용이 같으면 쓰지 않는다 — mtime 이 바뀌면 vite/tsc watch 가 쓸데없이 재빌드한다.
  if (fs.existsSync(file) && fs.readFileSync(file, 'utf8') === body) return
  fs.mkdirSync(path.dirname(file), { recursive: true })
  fs.writeFileSync(file, body)
}

async function main() {
  const ifMissing = process.argv.includes('--if-missing')
  if (ifMissing && fs.existsSync(OUT_TS) && fs.existsSync(OUT_MAIN) && fs.existsSync(OUT_JSON)) return

  // --if-missing 으로 한쪽만 없을 때는 이미 골라둔 제품을 유지한다.
  const already = fs.existsSync(OUT_TS)
    ? /products\/([^/]+)\/profile/.exec(fs.readFileSync(OUT_TS, 'utf8'))?.[1]
    : undefined
  const id = process.env.APP_MODE || (ifMissing ? already : undefined) || 'twixy'

  const profilePath = path.join(ROOT, 'products', id, 'profile.ts')
  if (!fs.existsSync(profilePath)) {
    const known = fs.readdirSync(path.join(ROOT, 'products'))
      .filter((d) => fs.existsSync(path.join(ROOT, 'products', d, 'profile.ts')))
    console.error(`[write-product] unknown APP_MODE "${id}" — expected one of: ${known.join(', ')}`)
    process.exit(1)
  }
  const { profile } = (await import(pathToFileURL(profilePath).href)) as { profile: ProductProfile }
  if (profile.id !== id) {
    console.error(`[write-product] products/${id}/profile.ts declares id "${profile.id}" — folder and id must match`)
    process.exit(1)
  }

  writeIfChanged(OUT_TS,
`// AUTO-GENERATED by scripts/write-product.ts — do not edit, do not commit.
// 현재 빌드 대상 제품. 바꾸려면 APP_MODE=<id> 로 dev/build 스크립트를 실행한다.
export { profile as PRODUCT } from '../../products/${id}/profile'
`)
  // 제품의 메인 프로세스 코드 (있으면). 코어의 electron/product-ipc.ts 가 import 한다.
  const hasMain = fs.existsSync(path.join(ROOT, 'products', id, 'electron', 'index.ts'))
  writeIfChanged(OUT_MAIN, hasMain
    ? `// AUTO-GENERATED by scripts/write-product.ts — do not edit, do not commit.\nexport { registerMain } from '../../products/${id}/electron/index'\n`
    : `// AUTO-GENERATED by scripts/write-product.ts — do not edit, do not commit.\n// 이 제품은 메인 프로세스 확장이 없다.\nimport type { ProductMainContext } from './types'\nexport function registerMain(_ctx: ProductMainContext): void {}\n`)
  writeIfChanged(OUT_JSON, JSON.stringify(profile, null, 2) + '\n')
  console.log(`[write-product] ${id}`)
}

main()
